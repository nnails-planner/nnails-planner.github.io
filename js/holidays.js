const cache = new Map();

function buildYear(y) {
  const map = new Map();
  const add = (date, h, n) => {
    const cur = map.get(date) || { h: [], n: [] };
    if (h) cur.h.push({ name: h[0], off: !!h[1] });
    if (n) cur.n.push(n);
    map.set(date, cur);
  };
  for (const [md, v] of Object.entries(FIXED)) {
    const date = `${y}-${md}`;
    (v.h || []).forEach((h) => add(date, h));
    if (v.n) add(date, null, v.n);
  }
  const e = orthodoxEaster(y);
  add(addDays(e, -43), ['Тодоровден', 0], 'Тодор, Теодора, Тодорка');
  add(addDays(e, -8), ['Лазаровден', 0], 'Лазар');
  add(addDays(e, -7), ['Цветница', 0], 'Цвета, Цветелина, Цветан, Лиляна, Роза, Виолета, Маргарита');
  add(addDays(e, -2), ['Разпети петък', 1]);
  add(addDays(e, -1), ['Велика събота', 1]);
  add(e, ['Великден', 1]);
  add(addDays(e, 1), ['Великден, втори ден', 1]);
  add(addDays(e, 39), ['Спасовден', 0], 'Спас, Спаска');
  return map;
}

export function dayMarks(date) {
  const y = Number(date.slice(0, 4));
  if (!cache.has(y)) cache.set(y, buildYear(y));
  return cache.get(y).get(date) || null;
}

export function mmdd(m, d) {
  return `${pad(m)}-${pad(d)}`;
}
